CREATE TABLE activity_logs (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id       bigint       REFERENCES users (id) ON DELETE SET NULL,
    action        varchar(100) NOT NULL,                 -- contoh: application.status_changed, data.exported
    subject_type  varchar(60),
    subject_id    bigint,
    properties    jsonb        NOT NULL DEFAULT '{}'::jsonb,
    ip_address    varchar(45),
    user_agent    varchar(255),
    created_at    timestamptz  NOT NULL DEFAULT now()
);
CREATE INDEX activity_logs_user_idx    ON activity_logs (user_id, created_at DESC);
CREATE INDEX activity_logs_subject_idx ON activity_logs (subject_type, subject_id);
CREATE INDEX activity_logs_action_idx  ON activity_logs (action, created_at DESC);
