-- ============================================================================
-- Skema Database — Website Company Profile & Pendaftaran Yayasan Padindi
-- DBMS   : PostgreSQL 15+
-- Backend: Laravel 12 (tabel bawaan Laravel seperti sessions, jobs, cache,
--          password_reset_tokens, personal_access_tokens dibuat oleh artisan
--          dan TIDAK disertakan di sini)
-- Versi  : 0.1 (Draft) — selaras dengan PRD v0.1
--
-- Konvensi:
--   * PK  : bigint identity
--   * Waktu: timestamptz
--   * Enum: varchar + CHECK (bukan tipe enum native, agar mudah dimigrasi)
--   * Soft delete: kolom deleted_at pada tabel inti
--   * NIK : disimpan terenkripsi di aplikasi (cast `encrypted` Laravel) pada
--           kolom text; kolom *_hash (SHA-256) dipakai untuk pencarian
--           dan deteksi duplikat
-- ============================================================================

CREATE EXTENSION IF NOT EXISTS pg_trgm;   -- pencarian nama (ILIKE) yang cepat


-- ============================================================================
-- 1. PENGGUNA, ROLE, HAK AKSES
-- ============================================================================

CREATE TABLE users (
    id                 bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name               varchar(150) NOT NULL,
    email              varchar(190) NOT NULL,
    phone              varchar(20),
    password           varchar(255) NOT NULL,
    user_type          varchar(20)  NOT NULL DEFAULT 'applicant',
    is_active          boolean      NOT NULL DEFAULT true,
    email_verified_at  timestamptz,
    last_login_at      timestamptz,
    remember_token     varchar(100),
    created_at         timestamptz  NOT NULL DEFAULT now(),
    updated_at         timestamptz  NOT NULL DEFAULT now(),
    deleted_at         timestamptz,
    CONSTRAINT users_user_type_check CHECK (user_type IN ('applicant', 'admin'))
);
CREATE UNIQUE INDEX users_email_unique ON users (lower(email)) WHERE deleted_at IS NULL;
CREATE INDEX users_user_type_idx ON users (user_type);

-- Catatan: jika memakai paket spatie/laravel-permission, lewati 4 tabel di bawah
-- dan gunakan migration bawaan paket tersebut.
CREATE TABLE roles (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name         varchar(60)  NOT NULL UNIQUE,   -- super_admin, admin_registration, admin_content
    label        varchar(120) NOT NULL,
    description  varchar(255),
    created_at   timestamptz  NOT NULL DEFAULT now(),
    updated_at   timestamptz  NOT NULL DEFAULT now()
);

CREATE TABLE permissions (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name         varchar(100) NOT NULL UNIQUE,   -- contoh: applications.verify
    label        varchar(150) NOT NULL,
    group_name   varchar(60),
    created_at   timestamptz  NOT NULL DEFAULT now(),
    updated_at   timestamptz  NOT NULL DEFAULT now()
);

CREATE TABLE permission_role (
    permission_id bigint NOT NULL REFERENCES permissions (id) ON DELETE CASCADE,
    role_id       bigint NOT NULL REFERENCES roles (id) ON DELETE CASCADE,
    PRIMARY KEY (permission_id, role_id)
);

CREATE TABLE role_user (
    role_id  bigint NOT NULL REFERENCES roles (id) ON DELETE CASCADE,
    user_id  bigint NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    PRIMARY KEY (role_id, user_id)
);
CREATE INDEX role_user_user_idx ON role_user (user_id);


-- ============================================================================
-- 2. MASTER DATA PENDAFTARAN
-- ============================================================================

CREATE TABLE education_units (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code           varchar(30)  NOT NULL,
    name           varchar(150) NOT NULL,
    slug           varchar(170) NOT NULL,
    level          varchar(20)  NOT NULL,
    tagline        varchar(255),
    description    text,
    address        text,
    phone          varchar(30),
    email          varchar(190),
    website_url    varchar(255),
    logo_path      varchar(255),
    cover_path     varchar(255),
    accreditation  varchar(30),
    principal_name varchar(150),
    facilities     jsonb        NOT NULL DEFAULT '[]'::jsonb,
    programs       jsonb        NOT NULL DEFAULT '[]'::jsonb,
    is_active      boolean      NOT NULL DEFAULT true,
    sort_order     integer      NOT NULL DEFAULT 0,
    created_at     timestamptz  NOT NULL DEFAULT now(),
    updated_at     timestamptz  NOT NULL DEFAULT now(),
    deleted_at     timestamptz,
    CONSTRAINT education_units_level_check
        CHECK (level IN ('paud', 'tk', 'sd', 'smp', 'sma', 'smk', 'other'))
);
CREATE UNIQUE INDEX education_units_code_unique ON education_units (code) WHERE deleted_at IS NULL;
CREATE UNIQUE INDEX education_units_slug_unique ON education_units (slug) WHERE deleted_at IS NULL;

CREATE TABLE registration_periods (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name             varchar(150) NOT NULL,           -- "PPDB 2027/2028 Gelombang 1"
    academic_year    varchar(9)   NOT NULL,           -- "2027/2028"
    wave             smallint     NOT NULL DEFAULT 1,
    opens_at         timestamptz  NOT NULL,
    closes_at        timestamptz  NOT NULL,
    announcement_at  timestamptz,
    description      text,
    registration_fee numeric(12,2) NOT NULL DEFAULT 0, -- hanya informasi (pembayaran di luar lingkup fase ini)
    is_active        boolean      NOT NULL DEFAULT true,
    created_at       timestamptz  NOT NULL DEFAULT now(),
    updated_at       timestamptz  NOT NULL DEFAULT now(),
    deleted_at       timestamptz,
    CONSTRAINT registration_periods_dates_check CHECK (closes_at > opens_at),
    CONSTRAINT registration_periods_fee_check   CHECK (registration_fee >= 0)
);
CREATE INDEX registration_periods_window_idx ON registration_periods (is_active, opens_at, closes_at);

CREATE TABLE period_unit_quotas (
    id                    bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    registration_period_id bigint  NOT NULL REFERENCES registration_periods (id) ON DELETE CASCADE,
    education_unit_id      bigint  NOT NULL REFERENCES education_units (id) ON DELETE RESTRICT,
    quota                  integer NOT NULL,
    created_at             timestamptz NOT NULL DEFAULT now(),
    updated_at             timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT period_unit_quotas_quota_check CHECK (quota >= 0),
    CONSTRAINT period_unit_quotas_unique UNIQUE (registration_period_id, education_unit_id)
);

-- Daftar dokumen wajib yang dapat dikonfigurasi per jenis pendaftar dan per unit.
-- education_unit_id NULL = berlaku untuk semua unit.
CREATE TABLE document_requirements (
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    applicant_type    varchar(10)  NOT NULL,
    education_unit_id bigint       REFERENCES education_units (id) ON DELETE CASCADE,
    document_type     varchar(50)  NOT NULL,           -- birth_certificate, family_card, photo, ...
    label             varchar(150) NOT NULL,
    description       varchar(255),
    is_required       boolean      NOT NULL DEFAULT true,
    max_size_kb       integer      NOT NULL DEFAULT 2048,
    allowed_mimes     varchar(100) NOT NULL DEFAULT 'pdf,jpg,jpeg,png',
    max_files         smallint     NOT NULL DEFAULT 1,
    sort_order        integer      NOT NULL DEFAULT 0,
    is_active         boolean      NOT NULL DEFAULT true,
    created_at        timestamptz  NOT NULL DEFAULT now(),
    updated_at        timestamptz  NOT NULL DEFAULT now(),
    CONSTRAINT document_requirements_type_check CHECK (applicant_type IN ('student', 'teacher')),
    CONSTRAINT document_requirements_size_check CHECK (max_size_kb > 0),
    CONSTRAINT document_requirements_files_check CHECK (max_files >= 1)
);
CREATE UNIQUE INDEX document_requirements_unique
    ON document_requirements (applicant_type, COALESCE(education_unit_id, 0), document_type);

-- Penghitung nomor pendaftaran (aman terhadap konkurensi).
-- Pemakaian: INSERT ... ON CONFLICT (scope) DO UPDATE
--            SET last_number = registration_counters.last_number + 1 RETURNING last_number;
CREATE TABLE registration_counters (
    scope        varchar(60) PRIMARY KEY,              -- contoh: 'student-2027', 'teacher-2027'
    last_number  integer     NOT NULL DEFAULT 0,
    updated_at   timestamptz NOT NULL DEFAULT now()
);


-- ============================================================================
-- 3. PENDAFTARAN SISWA
