CREATE TABLE student_applications (
    id                     bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id                bigint       NOT NULL REFERENCES users (id) ON DELETE RESTRICT,
    registration_period_id bigint       NOT NULL REFERENCES registration_periods (id) ON DELETE RESTRICT,
    education_unit_id      bigint       NOT NULL REFERENCES education_units (id) ON DELETE RESTRICT,
    registration_number    varchar(30),                -- dibuat saat status berubah dari draft ke submitted
    track                  varchar(50),                -- jalur: reguler, prestasi, dll. (opsional)
    status                 varchar(25)  NOT NULL DEFAULT 'draft',
    current_step           smallint     NOT NULL DEFAULT 1,
    submitted_at           timestamptz,
    reviewed_by            bigint       REFERENCES users (id) ON DELETE SET NULL,
    reviewed_at            timestamptz,
    admin_note             text,
    declaration_accepted_at timestamptz,               -- pernyataan data benar
    consent_accepted_at    timestamptz,                -- persetujuan penggunaan data pribadi (UU PDP)
    created_at             timestamptz  NOT NULL DEFAULT now(),
    updated_at             timestamptz  NOT NULL DEFAULT now(),
    deleted_at             timestamptz,
    CONSTRAINT student_applications_status_check CHECK (status IN (
        'draft', 'submitted', 'in_review', 'revision_required',
        'verified', 'accepted', 'rejected', 'waitlisted')),
    CONSTRAINT student_applications_step_check CHECK (current_step BETWEEN 1 AND 5),
    CONSTRAINT student_applications_submitted_check CHECK (
        status = 'draft' OR (registration_number IS NOT NULL AND submitted_at IS NOT NULL))
);
CREATE UNIQUE INDEX student_applications_number_unique ON student_applications (registration_number);
CREATE INDEX student_applications_user_idx   ON student_applications (user_id);
CREATE INDEX student_applications_filter_idx ON student_applications (registration_period_id, education_unit_id, status);
CREATE INDEX student_applications_status_idx ON student_applications (status);

CREATE TABLE students (
    id                      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_application_id  bigint       NOT NULL UNIQUE REFERENCES student_applications (id) ON DELETE CASCADE,
    full_name               varchar(150) NOT NULL,
    gender                  char(1)      NOT NULL,       -- L / P
    birth_place             varchar(100) NOT NULL,
    birth_date              date         NOT NULL,
    nik                     text,                        -- terenkripsi di aplikasi
    nik_hash                char(64),                    -- SHA-256 untuk pencarian/duplikat
    nisn                    varchar(10),
    religion                varchar(30),
    address                 text         NOT NULL,
    village                 varchar(100),
    district                varchar(100),
    city                    varchar(100),
    province                varchar(100),
    postal_code             varchar(10),
    phone                   varchar(20),
    previous_school         varchar(150),
    previous_school_npsn    varchar(10),
    graduation_year         smallint,
    created_at              timestamptz  NOT NULL DEFAULT now(),
    updated_at              timestamptz  NOT NULL DEFAULT now(),
    CONSTRAINT students_gender_check CHECK (gender IN ('L', 'P'))
);
CREATE INDEX students_nik_hash_idx ON students (nik_hash);
CREATE INDEX students_full_name_trgm ON students USING gin (full_name gin_trgm_ops);

CREATE TABLE guardians (
    id                      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_application_id  bigint       NOT NULL REFERENCES student_applications (id) ON DELETE CASCADE,
    relationship            varchar(10)  NOT NULL,       -- father / mother / guardian
    full_name               varchar(150) NOT NULL,
    nik                     text,
    nik_hash                char(64),
    birth_year              smallint,
    education_level         varchar(50),
    occupation              varchar(100),
    income_range            varchar(50),                 -- opsional (konfirmasi dengan yayasan)
    phone                   varchar(20),
    email                   varchar(190),
    address                 text,
    is_primary_contact      boolean      NOT NULL DEFAULT false,
    created_at              timestamptz  NOT NULL DEFAULT now(),
    updated_at              timestamptz  NOT NULL DEFAULT now(),
    CONSTRAINT guardians_relationship_check CHECK (relationship IN ('father', 'mother', 'guardian')),
    CONSTRAINT guardians_unique_relationship UNIQUE (student_application_id, relationship)
);


