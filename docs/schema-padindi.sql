CREATE INDEX teacher_applications_nik_hash_idx ON teacher_applications (nik_hash);
CREATE INDEX teacher_applications_name_trgm   ON teacher_applications USING gin (full_name gin_trgm_ops);

CREATE TABLE teacher_educations (
    id                      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    teacher_application_id  bigint       NOT NULL REFERENCES teacher_applications (id) ON DELETE CASCADE,
    level                   varchar(20)  NOT NULL,       -- SMA, D3, S1, S2, S3
