    major                   varchar(150),
    graduation_year         smallint,
    gpa                     numeric(4,2),
    sort_order              integer      NOT NULL DEFAULT 0,
    created_at              timestamptz  NOT NULL DEFAULT now(),
    updated_at              timestamptz  NOT NULL DEFAULT now(),
    CONSTRAINT teacher_educations_gpa_check CHECK (gpa IS NULL OR (gpa >= 0 AND gpa <= 4.00))
);
CREATE INDEX teacher_educations_app_idx ON teacher_educations (teacher_application_id);

CREATE TABLE teacher_experiences (
    id                      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    teacher_application_id  bigint       NOT NULL REFERENCES teacher_applications (id) ON DELETE CASCADE,
    institution             varchar(200) NOT NULL,
    position                varchar(150) NOT NULL,
    start_date              date         NOT NULL,
    end_date                date,                         -- NULL = masih berjalan
    description             text,
    sort_order              integer      NOT NULL DEFAULT 0,
    created_at              timestamptz  NOT NULL DEFAULT now(),
    updated_at              timestamptz  NOT NULL DEFAULT now(),
    CONSTRAINT teacher_experiences_dates_check CHECK (end_date IS NULL OR end_date >= start_date)
);
CREATE INDEX teacher_experiences_app_idx ON teacher_experiences (teacher_application_id);

CREATE TABLE teacher_certifications (
    id                      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    teacher_application_id  bigint       NOT NULL REFERENCES teacher_applications (id) ON DELETE CASCADE,
    name                    varchar(200) NOT NULL,        -- mis. Sertifikat Pendidik
    issuer                  varchar(200),
    certificate_number      varchar(100),
    year                    smallint,
    created_at              timestamptz  NOT NULL DEFAULT now(),
    updated_at              timestamptz  NOT NULL DEFAULT now()
);
CREATE INDEX teacher_certifications_app_idx ON teacher_certifications (teacher_application_id);


-- ============================================================================
-- 5. DOKUMEN & RIWAYAT STATUS (polimorfik)
--    documentable_type / loggable_type memakai morph map Laravel:
--    'student_application' dan 'teacher_application'
-- ============================================================================

CREATE TABLE documents (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    documentable_type   varchar(40)  NOT NULL,
    documentable_id     bigint       NOT NULL,
    document_type       varchar(50)  NOT NULL,
    sequence            smallint     NOT NULL DEFAULT 1,  -- untuk dokumen bertipe sama lebih dari satu
    disk                varchar(30)  NOT NULL DEFAULT 'private',
    path                varchar(255) NOT NULL,
    original_name       varchar(255) NOT NULL,
    mime_type           varchar(100) NOT NULL,
    size_bytes          bigint       NOT NULL,
    verification_status varchar(10)  NOT NULL DEFAULT 'pending',
    verification_note   text,
    verified_by         bigint       REFERENCES users (id) ON DELETE SET NULL,
    verified_at         timestamptz,
    created_at          timestamptz  NOT NULL DEFAULT now(),
    updated_at          timestamptz  NOT NULL DEFAULT now(),
    deleted_at          timestamptz,
    CONSTRAINT documents_type_check CHECK (documentable_type IN ('student_application', 'teacher_application')),
    CONSTRAINT documents_verification_check CHECK (verification_status IN ('pending', 'valid', 'invalid')),
    CONSTRAINT documents_size_check CHECK (size_bytes > 0)
);
CREATE INDEX documents_owner_idx ON documents (documentable_type, documentable_id);
CREATE UNIQUE INDEX documents_slot_unique
    ON documents (documentable_type, documentable_id, document_type, sequence)
    WHERE deleted_at IS NULL;

CREATE TABLE application_status_logs (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    loggable_type varchar(40)  NOT NULL,
    loggable_id   bigint       NOT NULL,
    from_status   varchar(25),
    to_status     varchar(25)  NOT NULL,
    note          text,
    changed_by    bigint       REFERENCES users (id) ON DELETE SET NULL,
    created_at    timestamptz  NOT NULL DEFAULT now(),
    CONSTRAINT application_status_logs_type_check
        CHECK (loggable_type IN ('student_application', 'teacher_application'))
);
CREATE INDEX application_status_logs_owner_idx
    ON application_status_logs (loggable_type, loggable_id, created_at);


